import React from 'react';
import { useAppData, useAppActions } from '../App';

const tabs = [
  { id: 'dashboard', label: 'Home', icon: HomeIcon },
  { id: 'log', label: 'Log', icon: PlusIcon },
  { id: 'history', label: 'History', icon: ChartIcon },
  { id: 'circle', label: 'Circle', icon: UsersIcon },
  { id: 'settings', label: 'Settings', icon: GearIcon }
];

export default function BottomNav() {
  const { view } = useAppData();
  const { navigate } = useAppActions();

  return (
    <nav className="fixed bottom-0 left-0 right-0 bg-surface-mid border-t border-white/5 safe-bottom z-50">
      <div className="flex items-center justify-around max-w-lg mx-auto h-16">
        {tabs.map(tab => {
          const active = view === tab.id;
          return (
            <button
              key={tab.id}
              onClick={() => navigate(tab.id)}
              className={`flex flex-col items-center gap-0.5 px-3 py-1 transition-colors ${
                active ? 'text-accent' : 'text-cream/40 hover:text-cream/60'
              }`}
            >
              <tab.icon active={active} />
              <span className="text-[10px] font-medium">{tab.label}</span>
            </button>
          );
        })}
      </div>
    </nav>
  );
}

